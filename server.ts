import express from 'express';
import { createServer as createViteServer } from 'vite';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

  app.use(express.json());

  // Gemini AI initialization
  const apiKey = process.env.GEMINI_API_KEY;
  const ai = apiKey
    ? new GoogleGenAI({
        apiKey: apiKey,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          },
        },
      })
    : null;

  // AI Chat Route for Civil Engineering Lab Assistant
  app.post('/api/chat', async (req, res) => {
    try {
      const { message, history, context } = req.body;
      if (!message || typeof message !== 'string') {
        return res.status(400).json({ error: 'Message string is required' });
      }

      if (!ai) {
        // Engineering response when API key is not yet set
        return res.json({
          reply: `### Concrete Strength AI Lab Assistant Note
*The server is operating in offline engineering rule-based mode (GEMINI_API_KEY not configured).*

**Civil Engineering Analysis for your query:**
"${message}"

1. **Hydration Kinetics & Abrams' Law**:
   Compressive strength ($f'_c$) is predominantly governed by the water-to-cementitious binder ratio ($w/b$). As $w/b$ decreases, capillary pore volume drops exponentially according to Powers' gel-space ratio theory, increasing compressive strength.
   
2. **Supplementary Cementitious Materials (SCMs)**:
   - **Blast Furnace Slag (GGBS)**: Latent hydraulic; reacts with $Ca(OH)_2$ released during cement hydration to form secondary C-S-H gel. Enhances long-term (56+ day) strength and sulfate resistance.
   - **Fly Ash (Class F/C)**: Pozzolanic; lowers early heat of hydration and improves particle packing and rheology (ball-bearing effect).

3. **Superplasticizers (PCE Admixtures)**:
   Polycarboxylate ether polymers introduce steric repulsion between flocculated cement grains. This unlocks trapped water, enabling a 15–30% water reduction while sustaining required workability (e.g. 100–180 mm slump).

4. **Lab Standard Compliance**:
   All predictive values generated by Random Forest and inverse optimization models represent statistical estimates. ASTM C39 cylinder testing, ASTM C143 slump checks, and laboratory trial batches per ACI 211.1 / IS 10262 remain legally mandatory for structural design certification.`,
        });
      }

      const systemInstruction = `You are the Concrete Strength AI Lab Assistant, an expert Civil & Materials Engineer for Exercise 11 in Civil Engineering Data Analytics.
You specialize in:
- The UCI Concrete Compressive Strength dataset (I-Cheng Yeh, 1998; 1030 laboratory concrete batches).
- Portland cement hydration kinetics, C-S-H gel formation, calcium hydroxide Ca(OH)2, capillary porosity, and microstructural development.
- Pozzolanic and latent hydraulic mechanisms of Supplementary Cementitious Materials (Blast Furnace Slag, Fly Ash).
- Chemical admixtures: Polycarboxylate ether (PCE) superplasticizers, water reduction, steric hindrance, slump retention, and rheology.
- Aggregate packing (Coarse & Fine Aggregate grading, fineness modulus, void ratios).
- Machine learning regression models (Random Forest, Decision Trees, Linear Regression, feature importances, R², RMSE, MAE).
- Inverse mix design optimization and its physical constraints.
- International concrete standards: ACI 211.1, ACI 318, ASTM C39 (compressive strength of cylindrical specimens), ASTM C192 (making and curing concrete test specimens), IS 10262, BS EN 206.

Always provide concise, mathematically rigorous, and practically relevant civil engineering insights. Use markdown formatting with clear headings, bullet points, and equations where helpful. Remind users that ML predictions are screening tools and that laboratory trial batches and certified code checks are mandatory before construction execution.`;

      const contents: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = [];

      if (context) {
        contents.push({
          role: 'user',
          parts: [
            {
              text: `[Active Lab Context]:\nCurrent Mix Parameters: ${JSON.stringify(
                context.currentMix || {}
              )}\nTarget Requirements: ${JSON.stringify(
                context.target || {}
              )}\nModel Performance: ${JSON.stringify(context.modelMetrics || {})}`,
            },
          ],
        });
        contents.push({
          role: 'model',
          parts: [
            {
              text: 'Understood. I have absorbed your current mix design inputs, target strength goals, and machine learning model metrics into my engineering analysis context.',
            },
          ],
        });
      }

      if (Array.isArray(history)) {
        for (const item of history.slice(-6)) {
          if (item && item.text && (item.role === 'user' || item.role === 'model')) {
            contents.push({
              role: item.role,
              parts: [{ text: item.text }],
            });
          }
        }
      }

      contents.push({
        role: 'user',
        parts: [{ text: message }],
      });

      // Timeout race in case of external network latency
      const timeoutPromise = new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error('AI assistant response timed out')), 15000)
      );

      const response = await Promise.race([
        ai.models.generateContent({
          model: 'gemini-3.8-flash',
          contents,
          config: {
            systemInstruction,
            temperature: 0.7,
          },
        }),
        timeoutPromise,
      ]);

      const replyText = response.text || 'No response generated from model.';
      return res.json({ reply: replyText });
    } catch (err: unknown) {
      console.error('Gemini error:', err);
      const message = err instanceof Error ? err.message : 'Unknown error';
      return res.status(500).json({
        error: 'Failed to process engineering assistant query: ' + message,
      });
    }
  });

  // Health route
  app.get('/api/health', (_req, res) => {
    res.json({
      status: 'ok',
      geminiConfigured: !!apiKey,
      dataset: 'UCI Concrete Compressive Strength (1030 samples)',
    });
  });

  // Vite in dev or static files in production
  if (process.env.NODE_ENV === 'production') {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`[Concrete Lab] Server running on http://0.0.0.0:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('[Concrete Lab] Failed to start server:', err);
  process.exit(1);
});
